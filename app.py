COURSE_BY_SLUG = {course["slug"]: course for course in COURSES}
COURSES_METRIC.set(len(COURSES))
LESSONS_METRIC.set(sum(len(course["lessons"]) for course in COURSES))


@app.before_request
def start_request_timer():
    g.request_started = perf_counter()


@app.after_request
def observe_request(response):
    from flask import request
    if request.endpoint not in {"metrics_endpoint", "static"}:
        endpoint = request.endpoint or "unknown"
        REQUESTS.labels(endpoint=endpoint, status=str(response.status_code)).inc()
        if hasattr(g, "request_started"):
            LATENCY.labels(endpoint=endpoint).observe(perf_counter() - g.request_started)
    return response


@app.context_processor
def shared_template_values():
    return {"deployment_mode": os.environ.get("DEPLOYMENT_MODE", "Локально"), "current_user": getattr(g, "user", None)}


@app.get("/")
def index():
    return render_template("index.html", courses=COURSES)


@app.get("/courses/<slug>")
def course_page(slug):
    course = COURSE_BY_SLUG.get(slug)
    if course is None:
        abort(404)
    return render_template("course.html", course=course)


@app.get("/courses/<slug>/lessons/<int:number>")
def lesson_page(slug, number):
    course = COURSE_BY_SLUG.get(slug)
    if course is None or not 1 <= number <= len(course["lessons"]):
        abort(404)
    return render_template(
        "lesson.html",
        course=course,
        lesson=course["lessons"][number - 1],
        number=number,
        previous=number - 1 if number > 1 else None,
        following=number + 1 if number < len(course["lessons"]) else None,
    )


@app.get("/progress")
def progress_page():
    return render_template("progress.html", courses=COURSES)


@app.get("/health")
def health():
    return {"status": "ok"}


@app.get("/metrics")
def metrics_endpoint():
    USERS.set(count_users())
    return generate_latest(REGISTRY), 200, {"Content-Type": CONTENT_TYPE_LATEST}


@app.errorhandler(404)
def not_found(_error):
    return render_template("404.html"), 404


if __name__ == "__main__":
    app.run(host="0.0.0.0", port=8080)
